MIN_SOL_SPENT         = 0.15    # Require >= 0.15 SOL real buy (skips dust / spam)
CONFLUENCE_WINDOW_SEC = 300     # 5-minute window to detect 2+ smart wallets entering the same coin
REQUIRE_CONFLUENCE    = False   # If True, only trade when >=2 tracked wallets buy; if False, 1 wallet buys sub-$45k Pump.fun coins
POLL_CYCLE_SLEEP      = 1.2     # Delay between individual wallet polls (keeps Helius usage tiny)

# State
_last_sig_by_wallet: Dict[str, Optional[str]] = {}
_recent_buys: Dict[str, Dict[str, float]] = {}   # mint -> {wallet: ts}
_triggered_mints: Dict[str, int] = {}            # mint -> highest buyer_count already triggered


def load_smart_wallets() -> List[dict]:
    """Load vetted smart-money wallets from data/smart_wallets.json."""
    if not os.path.exists(WALLETS_FILE):
        return []
    try:
        with open(WALLETS_FILE, "r", encoding="utf-8") as f:
            data = json.load(f)
        if isinstance(data, list):
            return [w for w in data if isinstance(w, dict) and w.get("wallet") and len(w["wallet"]) >= 32]
    except Exception as e:
        log.error(f"Could not read {WALLETS_FILE}: {e}")
    return []


async def get_latest_signatures(session: aiohttp.ClientSession, wallet: str, limit: int = 5) -> List[dict]:
    payload = {
        "jsonrpc": "2.0",
        "id": 1,
        "method": "getSignaturesForAddress",
        "params": [wallet, {"limit": limit}],
    }
    try:
        async with session.post(RPC_URL, json=payload, timeout=aiohttp.ClientTimeout(total=8)) as resp:
            if resp.status != 200:
                return []
            data = await resp.json(content_type=None)
            return data.get("result") or []
    except Exception:
        return []


async def get_transaction(session: aiohttp.ClientSession, signature: str) -> Optional[dict]:
    payload = {
        "jsonrpc": "2.0",
        "id": 1,
        "method": "getTransaction",
        "params": [signature, {"encoding": "jsonParsed", "maxSupportedTransactionVersion": 0}],
    }
    try:
        async with session.post(RPC_URL, json=payload, timeout=aiohttp.ClientTimeout(total=8)) as resp:
            if resp.status != 200:
                return None
            data = await resp.json(content_type=None)
            return data.get("result")
    except Exception:
        return None


def parse_buy_from_tx(tx: dict, wallet: str) -> Optional[str]:
    """
    Detect a genuine memecoin BUY by `wallet`:
      - Transaction succeeded (`err is None`)
      - Wallet's native SOL balance decreased by >= MIN_SOL_SPENT
      - Wallet's token balance for a non-stable mint increased significantly
    """
    try:
        meta = tx.get("meta")
        if not meta or meta.get("err") is not None:
            return None

        # Verify wallet actually spent >= MIN_SOL_SPENT SOL (rules out airdrops/dust)
        acct_keys = ((tx.get("transaction") or {}).get("message") or {}).get("accountKeys") or []
        wallet_idx = None
        for idx, k in enumerate(acct_keys):
            pk = k["pubkey"] if isinstance(k, dict) else k
            if pk == wallet:
                wallet_idx = idx
                break
        if wallet_idx is not None:
            pre_lam  = (meta.get("preBalances") or [0])[wallet_idx]
            post_lam = (meta.get("postBalances") or [0])[wallet_idx]
            sol_spent = (pre_lam - post_lam) / 1e9
            if sol_spent < MIN_SOL_SPENT:
                return None

        pre_map: Dict[str, float] = {}
        for b in (meta.get("preTokenBalances") or []):
            if b.get("owner") == wallet:
                pre_map[b["mint"]] = float((b.get("uiTokenAmount") or {}).get("uiAmount") or 0.0)

        for b in (meta.get("postTokenBalances") or []):
            if b.get("owner") != wallet:
                continue
            mint = b.get("mint") or ""
            if not mint or mint in STABLE_AND_BASE_MINTS:
                continue
            post_amt = float((b.get("uiTokenAmount") or {}).get("uiAmount") or 0.0)
            pre_amt  = pre_map.get(mint, 0.0)
            if post_amt > pre_amt and (post_amt - pre_amt) >= 50_000:
                return mint
    except Exception:
        return None
    return None


async def monitor_whale(wallet_pubkey: str = "", private_key_b58: str = ""):
    """Main async loop monitoring all vetted smart-money wallets for buys & multi-wallet confluence."""
    wallets = load_smart_wallets()
    if not wallets:
        log.info("No smart wallets configured in data/smart_wallets.json. Run 'python3 mine_wallets.py' to auto-mine winners.")
        return

    wallet_addrs = [w["wallet"] for w in wallets]
    label_map = {w["wallet"]: w.get("label") or w["wallet"][:6] for w in wallets}
    log.info(
        f"Starting Smart-Money Tracker for {len(wallet_addrs)} vetted wallet(s) "
        f"(Confluence-only={REQUIRE_CONFLUENCE}, Min buy={MIN_SOL_SPENT} SOL)"
    )

    connector = aiohttp.TCPConnector(ssl=False)
    async with aiohttp.ClientSession(connector=connector) as session:
        # Seed latest signature per wallet on boot so we don't replay old historical buys
        for w in wallet_addrs:
            sigs = await get_latest_signatures(session, w, limit=1)
            _last_sig_by_wallet[w] = sigs[0]["signature"] if sigs else None
            await asyncio.sleep(0.25)

        while True:
            try:
                now = time.time()
                # Prune stale confluence entries older than 5m
                for m in list(_recent_buys.keys()):
                    _recent_buys[m] = {w: ts for w, ts in _recent_buys[m].items() if (now - ts) <= CONFLUENCE_WINDOW_SEC}
                    if not _recent_buys[m]:
                        _recent_buys.pop(m, None)

                for w in wallet_addrs:
                    sigs = await get_latest_signatures(session, w, limit=5)
                    if not sigs:
                        await asyncio.sleep(POLL_CYCLE_SLEEP)
                        continue

                    last_seen = _last_sig_by_wallet.get(w)
                    new_sigs = []
                    for s_info in sigs:
                        sg = s_info["signature"]
                        if sg == last_seen:
                            break
                        if s_info.get("err") is None:
                            new_sigs.append(sg)

                    if new_sigs:
                        _last_sig_by_wallet[w] = sigs[0]["signature"]
                        for sg in reversed(new_sigs):
                            tx = await get_transaction(session, sg)
                            if not tx:
                                continue
                            mint = parse_buy_from_tx(tx, w)
                            if not mint:
                                continue

                            # Record buy in 5-minute confluence window
                            buyers = _recent_buys.setdefault(mint, {})
                            buyers[w] = time.time()
                            buyer_cnt = len(buyers)
                            buyer_labels = ", ".join(label_map.get(bw, bw[:6]) for bw in buyers.keys())
                            log.info(f"SMART BUY | {label_map.get(w, w[:6])} bought {mint[:10]}.. ({buyer_cnt} wallet(s) in 5m)")

                            should_trigger = (buyer_cnt >= 2) or (not REQUIRE_CONFLUENCE and mint.endswith("pump"))
                            prev_trig = _triggered_mints.get(mint, 0)
                            if should_trigger and buyer_cnt > prev_trig:
                                _triggered_mints[mint] = buyer_cnt
                                from autotrader import on_whale_buy
                                asyncio.create_task(on_whale_buy(
                                    session=None,
                                    mint=mint,
                                    wallet_pubkey=wallet_pubkey,
                                    private_key_b58=private_key_b58,
                                    buyer_count=buyer_cnt,
                                    wallet_labels=buyer_labels,
                                ))

                    await asyncio.sleep(POLL_CYCLE_SLEEP)
            except asyncio.CancelledError:
                raise
            except Exception as e:
                log.error(f"monitor_whale recovered from error: {e}")
                await asyncio.sleep(5)
