"""
whale_tracker.py — Multi-Wallet Smart-Money & Confluence Tracker.

Monitors a curated basket of vetted profitable Solana trench wallets (loaded from
data/smart_wallets.json, generated by mine_wallets.py or edited manually) via Helius RPC.

Safety guards vs blind copy-trading:
  - Ignores dust buys (< 0.15 SOL spent) and stablecoins/WSOL.
  - Tracks a 5-minute multi-wallet confluence window (2+ tracked wallets buying the same mint).
  - Routes all triggers through autotrader.on_whale_buy -> check_rug_risk + check_creator_risk
    + check_buy_pressure + V5 exits (0.02 SOL uniform size, never blind 2x gambling).
"""

